"""Every number the paper's prose quotes, as LaTeX macros, from the result files.

    PYTHONPATH=. python experiments/make_paper_numbers.py \
        --authored results/plant_allpairs.csv --generated results/generated_allpairs.csv \
        --twin results/twin_episodes.csv --out build/numbers.tex

The prose then says \\authPaceStructFeas rather than a typed digit, so a re-run
cannot leave a stale number behind.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

CATS = {"act": "infeasible, actionable", "struct": "infeasible, structural", "dev": "feasible, deviation",
        "none": "feasible, no change", "unrep": "infeasible, unrepairable"}
METHODS = {"Pace": "pace", "PaceOpt": "pace-opt", "Rec": "recourse", "Unc": "unconstrained", "Sem": "semantic",
           "Rnd": "random", "PaceNoattr": "pace-noattr", "PacePooled": "pace-pooled",
           "RecAct": "recourse-act", "UncAct": "unconstrained-act"}
METRICS = {"R": "recall_at_k", "Act": "actionable_fraction", "Feas": "feasibility_recovery",
           "Rec": "num_returned", "Ms": "runtime_ms"}


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def count(n: int) -> str:
    """A task count with a LaTeX thousands separator, as in 16{,}852."""
    return f"{n:,}".replace(",", "{,}")


def block(prefix: str, df: pd.DataFrame, out: list) -> None:
    key = ["scenario", "agent", "start", "goal"]
    tasks = df.drop_duplicates(key)
    out.append(macro(prefix + "Tasks", count(len(tasks))))
    out.append(macro(prefix + "Plants", df.scenario.nunique()))
    for ck, cat in CATS.items():
        n = int((tasks.cat == cat).sum())
        out.append(macro(prefix + "N" + ck.capitalize(), count(n)))
        sub = df[df.cat == cat]
        for mk, method in METHODS.items():
            row = sub[sub.method == method]
            for xk, col in METRICS.items():
                if len(row):
                    v = row[col].mean()
                    txt = f"{v:.0f}" if col == "runtime_ms" else f"{v:.1f}" if col == "num_returned" else f"{v:.2f}"
                else:
                    txt = "--"
                out.append(macro(f"{prefix}{mk}{xk}{ck.capitalize()}", txt))
    # overall runtime per method
    for mk, method in METHODS.items():
        row = df[df.method == method]
        out.append(macro(f"{prefix}{mk}Ms", f"{row.runtime_ms.mean():.0f}" if len(row) else "--"))
    # missions
    m = df[df.goal.str.startswith("pick_")]
    mt = m.drop_duplicates(key)
    out.append(macro(prefix + "Missions", count(len(mt))))
    for ck, cat in CATS.items():
        out.append(macro(prefix + "MissionN" + ck.capitalize(), count(int((mt.cat == cat).sum()))))
    # structural tasks pace repairs that recourse does not, and vice versa
    s = df[df.cat == CATS["struct"]]
    piv = s.pivot_table(index=key, columns="method", values="feasibility_recovery", aggfunc="first")
    if "pace" in piv and "recourse" in piv:
        out.append(macro(prefix + "PaceNotRec", count(int(((piv["pace"] == 1) & (piv["recourse"] == 0)).sum()))))
        out.append(macro(prefix + "RecNotPace", count(int(((piv["recourse"] == 1) & (piv["pace"] == 0)).sum()))))
    # how often recourse returns nothing on structural tasks it fails
    r = s[(s.method == "recourse") & (s.feasibility_recovery == 0)]
    out.append(macro(prefix + "RecStructFailNothing", count(int((r.num_returned == 0).sum()))))
    out.append(macro(prefix + "RecStructFail", count(len(r))))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--authored", default="results/plant_allpairs.csv")
    ap.add_argument("--generated", default="results/generated_allpairs.csv")
    ap.add_argument("--twin", default="results/twin_episodes.csv")
    ap.add_argument("--out", default="build/numbers.tex")
    a = ap.parse_args()
    out: list = ["% generated by experiments/make_paper_numbers.py -- do not edit\n"]
    for prefix, path in (("auth", a.authored), ("gen", a.generated)):
        if Path(path).exists():
            block(prefix, pd.read_csv(path), out)
        else:                                            # placeholders, so the paper compiles
            out.append(macro(prefix + "Tasks", "--") + macro(prefix + "Plants", "--")
                       + macro(prefix + "Missions", "--"))
            for ck in CATS:
                out.append(macro(prefix + "N" + ck.capitalize(), "--")
                           + macro(prefix + "MissionN" + ck.capitalize(), "--"))
                for mk in METHODS:
                    for xk in METRICS:
                        out.append(macro(f"{prefix}{mk}{xk}{ck.capitalize()}", "--"))
            for mk in METHODS:
                out.append(macro(f"{prefix}{mk}Ms", "--"))
            for name in ("PaceNotRec", "RecNotPace", "RecStructFailNothing", "RecStructFail"):
                out.append(macro(prefix + name, "--"))
    twin_names = ("twinroutes", "twinverified", "twinrefuted", "twinpassable", "twinfeasible", "twinsound",
                  "twinnamed", "twinblocked")
    if Path(a.twin).exists():
        import subprocess, sys
        tex = Path(a.out).with_name("twin_numbers.tex")
        subprocess.run([sys.executable, "experiments/summarise_twin.py", "--input", a.twin, "--tex", str(tex)],
                       check=True, capture_output=True)
        out.append(tex.read_text())
        tex.unlink()
    else:
        out += [macro(n, "--") for n in twin_names]
    Path(a.out).write_text("".join(out))
    print(f"wrote {a.out} ({len(out)} macros)")


if __name__ == "__main__":
    main()
